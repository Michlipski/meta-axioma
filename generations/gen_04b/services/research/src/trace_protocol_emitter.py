"""Sovereign Research Service TRACE Protocol Specification Emitter (`soc_g4b_research`).

Enforces:
- Invariant [L1-G4B-002]: Zero-Code Research Boundary (Solely emits specifications, contracts, and TRACE models).
- Invariant [L1-G3B-000]: Waterloo Situation of Concern (SoC) Normalization.
- Invariant [L1-G3B-011]: Universal Contract & Statechart IR.
- Invariant [INV-G4B-TRACE-001]: TRACE-AST Bijectivity & Declarative Conformance.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import json
import os
from pathlib import Path
import time
from typing import Any, Dict, List, Optional, Set, Tuple


@dataclass(frozen=True)
class TracePackageSpecification:
    """Complete declarative TRACE package generated by the research service."""
    app_id: str
    generation: str
    overview_md: str
    stack_md: str
    personas: Dict[str, str]
    domains: Dict[str, str]
    flows: Dict[str, str]
    emitted_at_unix_ms: int = field(default_factory=lambda: int(time.time() * 1000))


class TraceProtocolEmitter:
    """Translates research deliverables into formal, standardized TRACE markdown packages."""

    def __init__(self, researcher_id: str = "node_research_trace_emitter") -> None:
        self.researcher_id = researcher_id

    def emit_overview(
        self,
        app_id: str,
        name: str,
        generation: str,
        port: int,
        tagline: str,
        key_capabilities: List[str],
        glossary: Dict[str, str],
    ) -> str:
        """Synthesizes trace/overview.md."""
        cap_bullets = "\n".join([f"{i+1}. **{c.split(':')[0]}:** {c.split(':')[1] if ':' in c else c}" for i, c in enumerate(key_capabilities)])
        glossary_bullets = "\n".join([f"- **{k}:** {v}" for k, v in glossary.items()])

        return f"""---
name: {name}
app_id: {app_id}
generation: {generation}
port: {port}
---

# {name}

{tagline}

---

## What This System Does

{cap_bullets}

---

## Global Glossary

{glossary_bullets}
"""

    def emit_stack(
        self,
        app_id: str,
        stack_name: str,
        generation: str,
        port: int,
        subnet: str,
        invariants: List[str],
        defaults: Dict[str, Any],
    ) -> str:
        """Synthesizes trace/stack.md."""
        inv_bullets = "\n".join([f"- `{inv}`" for inv in invariants])
        default_bullets = "\n".join([f"- **{k}:** {v}" for k, v in defaults.items()])

        return f"""---
stack: {stack_name}
app_id: {app_id}
generation: {generation}
---

# {app_id} Infrastructure & System Defaults

## Execution Stack

### Core Runtime
- **Language / Runtime:** Python 3.14 (AsyncIO)
- **Port:** `{port}`
- **Subnet:** `{subnet}`
- **Tooling Constraints:** Zero paid external dependencies; pure standard library.

### Embodying Invariants
{inv_bullets}

---

## System Defaults
{default_bullets}
"""

    def emit_persona(
        self,
        persona_id: str,
        app_id: str,
        role_title: str,
        mindset: str,
        goals: List[str],
        capabilities: List[str],
    ) -> str:
        """Synthesizes trace/personas/<persona>.persona.md."""
        goal_bullets = "\n".join([f"- {g}" for g in goals])
        cap_bullets = "\n".join([f"- {c}" for c in capabilities])

        return f"""---
persona: {persona_id}
app_id: {app_id}
---

# PERSONA: {role_title}

{mindset}

---

## Goals & Mindset
{goal_bullets}

---

## Capabilities & Permissions
{cap_bullets}
"""

    def emit_domain(
        self,
        domain_name: str,
        related_domains: List[str],
        constraints: List[str],
        glossary: Dict[str, str],
        entities: Dict[str, Dict[str, Any]],
        events: Dict[str, Dict[str, Any]],
    ) -> str:
        """Synthesizes trace/domains/<domain>.domain.md."""
        rel_domains = "\n".join([f"  - {d}" for d in related_domains])
        constraint_bullets = "\n".join([f"- {c}" for c in constraints])
        glossary_bullets = "\n".join([f"- {k}: {v}" for k, v in glossary.items()])

        entity_blocks: List[str] = []
        for ent_name, ent_spec in entities.items():
            fields = ent_spec.get("fields", [])
            rules = ent_spec.get("rules", [])
            field_lines = "\n".join([f"- {f.get('name', '')}: {f.get('type', 'String')}" for f in fields])
            rule_lines = "\n".join([f"- {r}" for r in rules])
            block = f"# ENTITY: {ent_name}\nMUST HAVE:\n{field_lines}\n\nRULES:\n{rule_lines}"
            entity_blocks.append(block)
        all_entities = "\n\n".join(entity_blocks)

        event_blocks: List[str] = []
        for ev_name, ev_spec in events.items():
            trigger = ev_spec.get("trigger", "")
            payload_fields = ev_spec.get("payload", [])
            payload_lines = "\n".join([f"- {p}" for p in payload_fields])
            ev_block = f"# EVENT: {ev_name}\nTRIGGER:\n- {trigger}\nPAYLOAD:\n{payload_lines}"
            event_blocks.append(ev_block)
        all_events = "\n\n".join(event_blocks)

        return f"""---
domain: {domain_name}
related_domains:
{rel_domains}
---

CONSTRAINTS:
{constraint_bullets}

GLOSSARY:
{glossary_bullets}

{all_entities}

{all_events}
"""

    def emit_flow(
        self,
        flow_name: str,
        persona: str,
        domains: List[str],
        goal: str,
        steps: List[Dict[str, Any]],
    ) -> str:
        """Synthesizes trace/flows/<flow>.flow.md."""
        domain_lines = "\n".join([f"  - {d}" for d in domains])
        step_blocks: List[str] = []
        for i, s in enumerate(steps):
            title = s.get("title", f"STEP {i+1}")
            bullets = "\n".join([f"- {b}" for b in s.get("bullets", [])])
            step_blocks.append(f"## STEP {i+1}: {title}\n{bullets}")
        all_steps = "\n\n".join(step_blocks)

        return f"""---
flow: {flow_name}
persona: {persona}
domains:
{domain_lines}
---

# WORKFLOW: {flow_name}

> GOAL: {goal}

---

{all_steps}
"""
